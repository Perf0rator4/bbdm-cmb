"""Пути и гиперпараметры проекта.

Все значения читаются модулями пакета через ``from bbdm.config import ...``,
поэтому переопределять их в ноутбуке нужно ДО импорта остальных модулей,
либо (проще) передавать нужные значения аргументами в ``train()`` /
``run_inference()`` — все функции принимают их явно.
"""

# ---------------------------------------------------------------- пути -----

# Папка с тайлами Planck (960x960 .fits файлы)
PLANCK_DIR = ""

# Папка с тайлами ACT+Planck (960x960 .fits файлы)
ACT_DIR = ""

# Папка для сохранения чекпоинтов
CHECKPOINT_DIR = ""

# Папка проекта модели
PROJECT_DIR = ""

# ---------------------------------------------------------------- данные ---

PATCH_SIZE = 480
TRAIN_RATIO = 0.8
VAL_RATIO = 0.1
SEED = 42

# Максимальная доля нулевых (замаскированных) пикселей в патче.
MAX_ZERO_FRAC = 0.2

# Максимальная доля пикселей, где маски Planck и ACT НЕ совпадают
# (XOR валидных масок). У Planck и ACT DR6 разные футпринты, из-за чего
# на части патчей у Planck есть срезанный/замаскированный угол, которого
# нет у ACT (и наоборот). Такие пары портят и обучение, и спектральные
# метрики, поэтому отфильтровываются наравне с MAX_ZERO_FRAC.
MAX_MASK_MISMATCH_FRAC = 0.01

# --------------------------------------------------------------- модель ----

IN_CH = 1
BASE_CH = 64
TIME_DIM = 256
GROUPS = 8

# Подавать чистый патч Planck денойзеру отдельным каналом (cond_ch = 1).
# Шаг сэмплера точен, только если pred = E[y | x_t, x0]; сеть, видящая лишь
# x_t, учит E[y | x_t] и не может отделить вклад Planck от цели. Run 4
# измерил следствие: в полосе 0.1–0.3 на выход переехал весь Planck (там это
# в основном его приборный шум, 6.3x мощности цели). Даже точное E[y | x_t]
# оставляет там 0.57x мощности цели чистого шума, E[y | x_t, x0] -- ноль.
# Строго больше информации, поэтому оптимальный MSE хуже стать не может.
COND_ON_INPUT = True

# "resize_conv" -- nearest-resize + 3x3 conv (как в U-Net DDPM).
# "transpose"   -- ConvTranspose2d(k=2, s=2), архитектура run 3/4; оставлено
#                  только для загрузки старых чекпоинтов. Фаза 0.3 показала у
#                  неё анизотропный артефакт ровно на ±Найквисте.
UPSAMPLE = "resize_conv"

# ------------------------------------------------------------- диффузия ----

T = 1000  # число шагов диффузии
S = 200  # число шагов сэмплирования на инференсе
S_VAR = 0.5  # масштаб дисперсии моста (s)

# Шум, добавляемый в стартовое состояние обратного процесса:
#   x_T = planck + sqrt(ETA) * randn
# ETA=0 соответствует оригинальной статье BBDM (x_T = y ровно).
# ETA=0.01 использовался в run 3 и маскировал два противоположных дефекта:
# белый шум завышал мощность на высоких ell (TF ~ 2), а MSE-лосс её занижал
# (TF ~ 0.73 при ETA=0). Компенсация одного дефекта другим не даёт
# физической точности.
ETA = 0.0

# -------------------------------------------------------------- обучение ---

N_EPOCHS = 100
BATCH_SIZE = 32
LR = 1e-4
NUM_WORKERS = 2

# Вес спектрального члена в лоссе: L = MSE + SPECTRAL_WEIGHT * L1(log RAPSD).
# 0 -- чистый MSE. Run 4 с весом 0.1 дал TF 6-9 на высоких ell при r_ell ~ 0.
# Причина концептуальная: денойзер обязан выдавать АПОСТЕРИОРНОЕ СРЕДНЕЕ,
# которое при большом t по определению гладкое; недостающую дисперсию
# добавляет сэмплер (шум sqrt(delta_tilde) * z на каждом шаге). Требовать от
# выхода денойзера мощность полной реализации -- ошибка категории: сеть
# перестаёт гасить шум в середине цепочки, и он доезжает до выхода.
# Не возвращать без t-зависимой цели (см. CLAUDE.md §7.1).
SPECTRAL_WEIGHT = 0.0

# EMA начинается после ~10k шагов (~30 эпох при ~325 шагах/эпоху),
# дальше усредняет оставшиеся ~22k шагов.
EMA_START = 10000
EMA_DECAY = 0.995
GRAD_CLIP = 1.0

# ReduceLROnPlateau шагается РАЗ В ЭПОХУ, поэтому patience измеряется
# в эпохах (а не в шагах оптимизатора, как 3000 в статье).
SCHEDULER_FACTOR = 0.5
SCHEDULER_PATIENCE = 5

# Сид для валидационного лосса: t и шум в q_sample фиксируются, чтобы
# val-кривая была сравнима между эпохами (иначе и выбор "лучшего"
# чекпоинта, и ReduceLROnPlateau управляются шумом оценки).
VAL_SEED = 1234

# Спектральный монитор во время обучения: каждые MONITOR_EVERY эпох на
# MONITOR_N валидационных патчах прогоняется НАСТОЯЩИЙ сэмплер (MONITOR_S
# шагов) и печатаются TF / r_ell по полосам. Run 4 показал, что одношаговый
# лосс этот провал не видит вообще: val-лосс был нормальным, а TF на выходе
# сэмплера -- 9.5. Монитор ловит такое через эпоху, а не через 32 часа.
# ~15 с на эпоху при N=8, S=50. MONITOR_EVERY=0 выключает.
MONITOR_EVERY = 1
MONITOR_N = 8
MONITOR_S = 50
