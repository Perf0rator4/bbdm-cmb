# Спектральный монитор во время обучения: каждые MONITOR_EVERY эпох на первых
# MONITOR_N валидационных патчах прогоняется НАСТОЯЩИЙ сэмплер (MONITOR_S
# шагов) на EMA-весах и считаются TF / r_ell / r_in по полосам и PSNR. Run 4
# показал, что одношаговый лосс провал цепочки не видит вообще: val-лосс был
