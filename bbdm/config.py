# Вес спектрального члена в лоссе: L = MSE + SPECTRAL_WEIGHT * L1(log RAPSD).
# 0 -- чистый MSE. Run 4 с весом 0.1 дал TF 6-9 на высоких ell при r_ell ~ 0.
# Причина концептуальная: денойзер обязан выдавать АПОСТЕРИОРНОЕ СРЕДНЕЕ,
# которое при большом t по определению гладкое; недостающую дисперсию
# добавляет сэмплер (шум sqrt(delta_tilde) * z на каждом шаге). Требовать от
# выхода денойзера мощность полной реализации -- ошибка категории: сеть
# перестаёт гасить шум в середине цепочки, и он доезжает до выхода.
# Не возвращать без t-зависимой цели (см. CLAUDE.md §7.1).
SPECTRAL_WEIGHT = 0.0

# EMA начинается после ~10k шагов (~30 эпох при ~325 шагах/эпоху),
