"""Пути и гиперпараметры проекта.

Все значения читаются модулями пакета через ``from bbdm.config import ...``,
поэтому переопределять их в ноутбуке нужно ДО импорта остальных модулей,
либо (проще) передавать нужные значения аргументами в ``train()`` /
``run_inference()`` — все функции принимают их явно.
"""

# ---------------------------------------------------------------- пути -----

# Папка с тайлами Planck (960x960 .fits файлы)
PLANCK_DIR = ""

# Папка с тайлами ACT+Planck (960x960 .fits файлы)
ACT_DIR = ""

# Папка для сохранения чекпоинтов
CHECKPOINT_DIR = ""

# Папка проекта модели
PROJECT_DIR = ""

# ---------------------------------------------------------------- данные ---

PATCH_SIZE = 480
TRAIN_RATIO = 0.8
VAL_RATIO = 0.1
SEED = 42

# Максимальная доля нулевых (замаскированных) пикселей в патче.
MAX_ZERO_FRAC = 0.2

# Максимальная доля пикселей, где маски Planck и ACT НЕ совпадают
# (XOR валидных масок). У Planck и ACT DR6 разные футпринты, из-за чего
# на части патчей у Planck есть срезанный/замаскированный угол, которого
# нет у ACT (и наоборот). Такие пары портят и обучение, и спектральные
# метрики, поэтому отфильтровываются наравне с MAX_ZERO_FRAC.
MAX_MASK_MISMATCH_FRAC = 0.01

# --------------------------------------------------------------- модель ----

IN_CH = 1
BASE_CH = 64
TIME_DIM = 256
GROUPS = 8

# ------------------------------------------------------------- диффузия ----

T = 1000  # число шагов диффузии
S = 200  # число шагов сэмплирования на инференсе
S_VAR = 0.5  # масштаб дисперсии моста (s)

# Шум, добавляемый в стартовое состояние обратного процесса:
#   x_T = planck + sqrt(ETA) * randn
# ETA=0 соответствует оригинальной статье BBDM (x_T = y ровно).
# ETA=0.01 использовался в run 3 и маскировал два противоположных дефекта:
# белый шум завышал мощность на высоких ell (TF ~ 2), а MSE-лосс её занижал
# (TF ~ 0.73 при ETA=0). Компенсация одного дефекта другим не даёт
# физической точности — вместо этого ETA=0 + спектральный лосс (ниже).
ETA = 0.0

# -------------------------------------------------------------- обучение ---

N_EPOCHS = 100
BATCH_SIZE = 32
LR = 1e-4
NUM_WORKERS = 2

# Вес спектрального члена в лоссе: L = MSE + SPECTRAL_WEIGHT * L1(log RAPSD).
# Прямо штрафует отклонение Transfer Function от 1, вместо того чтобы
# полагаться на случайную взаимокомпенсацию дефектов.
# Рекомендуемый свип перед полным прогоном: {0.05, 0.1, 0.3} по ~20-30 эпох.
SPECTRAL_WEIGHT = 0.1

# EMA начинается после ~10k шагов (~30 эпох при ~325 шагах/эпоху),
# дальше усредняет оставшиеся ~22k шагов.
EMA_START = 10000
EMA_DECAY = 0.995
GRAD_CLIP = 1.0

# ReduceLROnPlateau шагается РАЗ В ЭПОХУ, поэтому patience измеряется
# в эпохах (а не в шагах оптимизатора, как 3000 в статье).
SCHEDULER_FACTOR = 0.5
SCHEDULER_PATIENCE = 5

# Сид для валидационного лосса: t и шум в q_sample фиксируются, чтобы
# val-кривая была сравнима между эпохами (иначе и выбор "лучшего"
# чекпоинта, и ReduceLROnPlateau управляются шумом оценки).
VAL_SEED = 1234
